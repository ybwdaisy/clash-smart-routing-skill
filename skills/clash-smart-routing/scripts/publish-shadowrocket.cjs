#!/usr/bin/env node
'use strict';
// Publish from the reviewed repository template only. Never read a device profile.
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const cp = require('node:child_process');
const crypto = require('node:crypto');
const exporter = require('./shadowrocket.cjs');
const ROOT = path.resolve(__dirname, '../../..');
const UPDATE_URL = 'https://raw.githubusercontent.com/ybwdaisy/clash-smart-routing-skill/main/shadowrocket/smart-routing.conf';
const BASE = path.join(__dirname, '../assets/shadowrocket-public-base.conf');
const GENERAL = new Set(['fallback-dns-server','bypass-system','skip-proxy','tun-excluded-routes','dns-server','ipv6','prefer-ipv6',
  'dns-fallback-system','dns-direct-system','icmp-auto-reply','always-reject-url-rewrite','private-ip-answer','dns-direct-fallback-proxy','update-url']);
const PUBLIC_URLS = new Set([UPDATE_URL, 'https://dns.alidns.com/dns-query', 'https://doh.pub/dns-query',
  ...exporter.REMOTES.map(r => r.url),
  'https://raw.githubusercontent.com/blackmatrix7/ios_rule_script/master/rule/Shadowrocket/ChinaMaxNoIP/ChinaMaxNoIP_Domain.list',
  'https://raw.githubusercontent.com/blackmatrix7/ios_rule_script/master/rule/Shadowrocket/ChinaMaxNoIP/ChinaMaxNoIP.list']);
const sha = b => crypto.createHash('sha256').update(b).digest('hex');
function validatePublic(text, generated = false) {
  let section = '', finals = 0, general = 0;
  const keys = new Set();
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim(); if (!line || line.startsWith('#') || line.startsWith(';')) continue;
    const match = line.match(/^\[([^\]]+)\]$/);
    if (match) {
      section = match[1];
      if (!['General','Rule','Host','URL Rewrite'].includes(section)) throw Error('Nonpublic/unsupported section in public profile');
      if (section === 'General') general++;
      continue;
    }
    if (section === 'General') {
      const pair = line.match(/^([a-z0-9-]+)\s*=\s*(.*)$/);
      if (!pair || !GENERAL.has(pair[1]) || keys.has(pair[1])) throw Error('Unsupported or duplicate public General setting');
      keys.add(pair[1]);
      if (pair[1] === 'update-url' && pair[2] !== UPDATE_URL) throw Error('Unexpected update URL');
      if (pair[1] !== 'update-url') for (const value of pair[2].split(',').map(s => s.trim())) {
        if (/https?:/.test(value)) { if (!PUBLIC_URLS.has(value)) throw Error('Nonpublic DNS URL'); }
        else if (!/^(true|false|system|localhost|\*\.local|captive\.apple\.com|[0-9./:]+)$/.test(value)) throw Error('Nonpublic General value');
      }
    } else if (section === 'Rule') {
      const fields = line.split(',');
      if (fields[0] === 'FINAL') {
        if (line !== 'FINAL,PROXY') throw Error('Public fallback must retain the selected PROXY');
        finals++; continue;
      }
      if (['RULE-SET','DOMAIN-SET'].includes(fields[0])) {
        if (fields.length !== 3 || !PUBLIC_URLS.has(fields[1]) || !['PROXY','DIRECT'].includes(fields[2])) throw Error('Unreviewed remote rule resource');
      } else {
        if (!['DOMAIN','DOMAIN-SUFFIX','DOMAIN-KEYWORD','USER-AGENT','IP-CIDR','IP-CIDR6','GEOIP'].includes(fields[0]) ||
          !fields[1] || !/^[a-zA-Z0-9._*%:/+\-]+$/.test(fields[1]) || !['PROXY','DIRECT'].includes(fields[2]) ||
          fields.length > 4 || (fields.length === 4 && fields[3] !== 'no-resolve')) throw Error('Unsupported public routing rule');
      }
    } else if (section === 'Host') {
      if (line !== 'localhost = 127.0.0.1') throw Error('Private Host mappings must not be published');
    } else if (section === 'URL Rewrite') {
      if (!["'^https?://(www.)?g.cn' 'https://www.google.com' 302", "'^https?://(www.)?google.cn' 'https://www.google.com' 302"].includes(line))
        throw Error('Private rewrites must not be published');
    } else throw Error('Unexpected content outside public sections');
  }
  if (general !== 1 || finals !== 1) throw Error('Expected one General section and one FINAL');
  if (generated && !text.includes('update-url = ' + UPDATE_URL)) throw Error('Generated profile missing update URL');
  return true;
}
function releaseText(text, revision, manifest) {
  validatePublic(text);
  if (!/^[a-f0-9]{40}$/.test(revision)) throw Error('A full source commit SHA is required');
  const sources = [...new Set([...Object.values(manifest.sources), ...Object.values(manifest.remoteSources || {})].map(s => s.url))];
  const header = ['# Generated by clash-smart-routing-skill; do not edit this remote file.',
    '# Source commit: ' + revision,
    '# Generator: https://github.com/ybwdaisy/clash-smart-routing-skill',
    '# Contains routing/DNS only. PROXY follows the node selected in Shadowrocket.',
    '# APNs proxy optimization is enabled in this profile; no automatic node selection.',
    '# This generated rule-data compilation is distributed under AGPL-3.0-or-later; see LICENSE-AGPL-3.0.txt.',
    '# Derived rule data: MetaCubeX/meta-rules-dat and SukkaW/Surge (Sukka data: AGPL-3.0).',
    ...sources.map(url => '# Rule source: ' + url), ''].join('\n');
  // The fixed base cannot contain another update URL, nor can private input be supplied.
  const output = header + text.replace(/^\[General\]$/m, '[General]\nupdate-url = ' + UPDATE_URL);
  validatePublic(output, true);
  return output;
}
function main(argv) {
  const args = {};
  while (argv.length) {
    const key = argv.shift();
    if (!['--source-dir','--http-proxy','--revision','--output-dir'].includes(key) || !argv.length || args[key]) throw Error('Unsupported publish argument');
    args[key] = argv.shift();
  }
  const revision = args['--revision'] || cp.execFileSync('git', ['rev-parse','HEAD'], {cwd:ROOT,encoding:'utf8'}).trim();
  const temp = fs.mkdtempSync(path.join(os.tmpdir(),'shadowrocket-publish-'));
  try {
    const base = fs.readFileSync(BASE,'utf8'); validatePublic(base);
    const candidate = path.join(temp,'candidate.conf');
    const result = exporter.main(['--input',BASE,'--output',candidate,'--dns','saving','--remote','on',
      ...(args['--source-dir'] ? ['--source-dir',args['--source-dir']] : []),
      ...(args['--http-proxy'] ? ['--http-proxy',args['--http-proxy']] : [])]);
    if (!result.apnsProxyProtected) throw Error('Expected existing APNs protection to survive');
    const manifest = JSON.parse(fs.readFileSync(candidate+'.manifest.json','utf8'));
    const output = releaseText(fs.readFileSync(candidate,'utf8'),revision,manifest);
    const target = path.resolve(args['--output-dir'] || path.join(ROOT,'shadowrocket'));
    fs.mkdirSync(target,{recursive:true});
    const report = {format:1,sourceCommit:revision,updateURL:UPDATE_URL,outputSha256:sha(output),
      baseSha256:sha(base),sources:manifest.sources,remoteSources:manifest.remoteSources,
      apnsProxyProtected:true,originalPublicRulesPreserved:true,dnsMode:'saving',noNodesOrSubscriptionCredentials:true};
    fs.writeFileSync(path.join(target,'smart-routing.conf'),output);
    fs.writeFileSync(path.join(target,'smart-routing.sources.json'),JSON.stringify(report,null,2)+'\n');
    return {output:path.join(target,'smart-routing.conf'),updateURL:UPDATE_URL,sourceCommit:revision,bytes:Buffer.byteLength(output),apnsProxyProtected:true};
  } finally { fs.rmSync(temp,{recursive:true,force:true}); }
}
if (require.main === module) { try {console.log(JSON.stringify(main(process.argv.slice(2)),null,2));} catch(e) {console.error(e.message);process.exitCode=1;} }
module.exports={validatePublic,releaseText,main,UPDATE_URL,BASE};
